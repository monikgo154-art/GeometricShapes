namespace Kite
{
    public class Rhombus
    {
        private string name;
        private double a;
        private double d1;
        private double d2;

        public Rhombus(string name, double a, double d1, double d2)
        {
            this.name = name;
            this.a = a;
            this.d1 = d1;
            this.d2 = d2;
        }
    }
}